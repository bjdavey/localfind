package com.localfind.data

import com.localfind.core.model.EMBEDDING_DIMENSION
import android.content.Context
import com.google.mediapipe.tasks.retrieval.components.SqliteVectorStore
import com.google.mediapipe.tasks.retrieval.components.VectorStore
import com.google.mediapipe.tasks.retrieval.model.RetrievalRecord
import java.io.File

/** Default filename for the SQLite-backed vector database in app files dir. */
private const val DATABASE_NAME = "localfind_vectors.db"

/**
 * Local vector store backed by MediaPipe's [SqliteVectorStore].
 *
 * Role in Architecture:
 * - Stores indexed chunks, their 768-dimensional float embeddings, original text snippet,
 *   and structured metadata (such as fileId, uri, name, type, and character/time location).
 * - Executes cosine similarity searches over stored embeddings to find nearest neighbors
 *   for search queries.
 * - Allows idempotent upserts and granular deletions by metadata (e.g., removing all chunks
 *   associated with a specific document when re-indexing or deleting).
 *
 * Implements [AutoCloseable] to ensure SQLite database connections are cleanly closed.
 */
class EmbeddingStore(
    private val vectorStore: VectorStore
) : AutoCloseable {

    companion object {
        /**
         * Factory function to create an instance of [EmbeddingStore] using [SqliteVectorStore].
         *
         * @param context Application context used to resolve the internal database path.
         */
        fun create(context: Context): EmbeddingStore {
            val dbFile = File(context.filesDir, DATABASE_NAME)
            val store = SqliteVectorStore(context, dbFile.absolutePath, EMBEDDING_DIMENSION)
            return EmbeddingStore(store)
        }
    }

    /**
     * Stores or updates a batch of records in a single database transaction.
     * Synchronized on `this` for thread safety.
     * Used when indexing an entire document's chunks to optimize write performance.
     */
    fun storeBatch(records: List<RetrievalRecord>) = synchronized(this) {
        vectorStore.upsert(records)
    }

    /**
     * Retrieves a single record by its unique ID, or returns null if not found.
     */
    fun get(id: String): RetrievalRecord? = synchronized(this) {
        vectorStore.get(listOf(id)).firstOrNull()
    }

    /**
     * Returns the total number of embedded chunk records stored in the vector database.
     */
    fun count(): Int = synchronized(this) {
        vectorStore.allRecordIds.size
    }

    /**
     * Deletes all records matching the given metadata filter criteria.
     *
     * Example:
     * `deleteByMetadata(mapOf("fileId" to fileUri))` deletes all chunks belonging
     * to a specific document before re-indexing or when a document is removed.
     */
    fun deleteByMetadata(metadata: Map<String, String>) = synchronized(this) {
        vectorStore.delete(metadata)
    }

    /**
     * Deletes all records and embeddings associated with the given file URI.
     *
     * Convenience method used when removing a file from the library or deleting its embeddings.
     */
    fun deleteByFileUri(fileUri: String) = synchronized(this) {
        deleteByMetadata(mapOf("fileId" to fileUri))
    }

    /**
     * Searches for the top-K nearest neighbors to the given query embedding using cosine similarity.
     * Synchronized on `this` to coordinate safely with ongoing SQLite transactions from indexing.
     *
     * @param queryEmbedding 768-dim vector generated by embedding the user's search query text.
     * @param topK Maximum number of matching records to return.
     * @param metadataFilter Optional filter (e.g. `mapOf("type" to "text")`) to restrict results.
     * @return List of [RetrievalRecord] ordered by relevance / similarity.
     */
    fun search(
        queryEmbedding: FloatArray,
        topK: Int,
        metadataFilter: Map<String, String>
    ): List<RetrievalRecord> = synchronized(this) {
        if (metadataFilter.isEmpty()) {
            vectorStore.search(queryEmbedding, topK)
        } else {
            vectorStore.search(queryEmbedding, topK, metadataFilter)
        }
    }

    /**
     * Closes the underlying SQLite vector database connection.
     */
    override fun close() = synchronized(this) {
        vectorStore.close()
    }
}
